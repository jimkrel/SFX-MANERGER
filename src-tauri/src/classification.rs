fn normalized(text: &str) -> String {
    let text = text.to_lowercase().replace('đ', "d");
    let ascii: String = DecomposingNormalizer::new_nfd()
        .normalize(&text)
        .chars()
        .filter(|c| !('\u{300}'..='\u{36f}').contains(c))
        .map(|c| if c.is_ascii_alphanumeric() { c } else { ' ' })
        .collect();
    ascii.split_whitespace().collect::<Vec<_>>().join(" ")
}

pub fn category(path: &str, name: &str) -> &'static str {
    let raw = format!("{path} {name}").to_lowercase();
    let spaced = raw
        .split(['_', '-', '.', '/', '\\'])
        .filter(|s| !s.is_empty())
        .collect::<Vec<_>>()
        .join(" ");
    for (label, words) in [
        ("Cinematic", CINEMATIC_CATEGORY),
        ("Foley", FOLEY_CATEGORY),
        ("Ambience", AMBIENCE_CATEGORY),
        ("UI / Digital", UI_CATEGORY),
        ("Nature", NATURE_CATEGORY),
    ] {
        if words.iter().any(|w| raw.contains(w) || spaced.contains(w)) {
            return label;
        }
    }
    "Khác"
}

pub fn audio_type(track: &Value) -> &'static str {
    let field = |key: &str| track[key].as_str().unwrap_or("");
    let genre = field("genre").to_lowercase();
    let duration = track["duration"].as_f64().unwrap_or_default();
    let contains = |s: &str, words: &[&str]| words.iter().any(|word| s.contains(word));
    if contains(&genre, SFX_GENRES) {
        return "SFX";
    }
    if contains(&genre, MUSIC_GENRES) {
        return "Music";
    }
    let name = format!(" {} ", normalized(field("name")));
    let matches = |words: &[&str]| words.iter().any(|w| name.contains(&format!(" {w} ")));
    match (matches(MUSIC_KEYWORDS), matches(SFX_KEYWORDS)) {
        (true, true) if duration < 30.0 => return "SFX",
        (true, _) => return "Music",
        (_, true) => return "SFX",
        _ => {}
    }
    for (value, excluded) in [
        (field("artist"), &["sound ideas", "boom library", "sfx"][..]),
        (field("album"), &["sfx", "sound effect", "foley"][..]),
    ] {
        if !value.trim().is_empty() && !contains(&normalized(value), excluded) {
            return "Music";
        }
    }
    let folder = field("path")
        .rsplit(['/', '\\'])
        .nth(1)
        .unwrap_or("")
        .to_lowercase();
    if contains(
        &folder,
        &[
            "music",
            "nhac",
            "song",
            "beat",
            "bgm",
            "soundtrack",
            "ost",
            "nhạc",
        ],
    ) {
        return "Music";
    }
    if duration < 60.0
        && contains(
            &folder,
            &[
                "sfx",
                "sound effect",
                "tieng dong",
                "foley",
                "stinger",
                "hieu ung",
            ],
        )
    {
        return "SFX";
    }
    if duration >= 60.0 || (duration >= 30.0 && track["bpm"].as_f64().unwrap_or_default() > 0.0) {
        "Music"
    } else {
        "SFX"
    }
}
